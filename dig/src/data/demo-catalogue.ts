/**
 * DIG demo catalogue (sample data).
 *
 * Every record here is clearly tagged `is_demo`. Artist / title / label / year
 * are editor-entered from well-known discographies and carry provenance
 * `human_curator` with a per-record confidence; nothing here is presented as
 * licensed metadata or a verified upload. Demo sources link to provider
 * *search* pages ("Find on YouTube"), never to a specific upload we have not
 * verified, so no link is invented.
 *
 * Deliberate test cases: a same-title collision ("Can You Feel It" x2), an
 * original + remix pair kept distinct, aliases (Larry Heard, Carl Craig,
 * Arthur Russell, Juan Atkins...), a sparse white-label record with no year
 * or label, and a record whose first source is marked unavailable.
 */

export interface DemoArtist {
  key: string;
  name: string;
  country?: string;
  aliases?: string[];
}
export interface DemoLabel {
  key: string;
  name: string;
  country?: string;
}
export interface DemoRecording {
  key: string;
  title: string;
  artist: string; // artist key
  year?: number;
  label?: string; // label key
  release?: string; // release title
  releaseType?: "single" | "ep" | "album" | "compilation";
  catalogue?: string;
  tags: string[]; // tag slugs
  disambiguation?: string;
  credits?: Array<{ artist: string; role: "remixer" | "featured" | "producer" | "composer" }>;
  confidence?: number; // metadata confidence 0..1 (default 0.85)
  sources?: Array<{
    provider: "demo";
    playability: "external_only" | "unavailable";
    note?: string;
  }>;
}
export interface DemoTag {
  slug: string;
  name: string;
  kind: "style" | "scene" | "mood" | "era" | "region";
}
export interface DemoRelation {
  from: string;
  to: string;
  type: "alias" | "member_of" | "collaborated_with";
}
export interface DemoEdge {
  from: string; // recording key
  to: string; // recording key
  relation: "remixed_by" | "collaborated_with" | "producer_overlap" | "similar_sound_unverified";
  weight?: number;
  provenance?: "human_curator" | "inferred";
  note?: string;
}
export interface DemoCuration {
  slug: string;
  title: string;
  description: string;
  seedRoute: boolean;
  items: Array<{ recording: string; note?: string }>;
}

